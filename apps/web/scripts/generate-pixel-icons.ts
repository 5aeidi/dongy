const used = readFileSync(join(import.meta.dirname, 'pixel-icons.txt'), 'utf8')
  .split(/\s+/)
  .filter(Boolean)
const available = new Set(
  readdirSync(svgDir).map((file) => file.replace(/\.svg$/, '')),
)
const kebab = (name: string) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase()

const entries: string[] = []
const missing: string[] = []
for (const name of used) {
  const source = ALIASES[name] ?? kebab(name)
  if (!available.has(source)) {
    missing.push(`${name} (${source})`)
    continue
  }
  const svg = readFileSync(join(svgDir, `${source}.svg`), 'utf8')
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/>\s+</g, '><')
    .trim()
  entries.push(`  ${name}: ${JSON.stringify(inner)},`)
}

writeFileSync(
  out,
  `// Generated by scripts/generate-pixel-icons.ts — do not edit.\n` +
    `// Icon art: pixelarticons (MIT), https://github.com/halfmage/pixelarticons\n\n` +
    `export const pixelIconMarkup: Record<string, string> = {\n${entries.join('\n')}\n}\n`,
)
console.log(`${entries.length} pixel icons written`)
if (missing.length) console.log(`kept as lucide: ${missing.join(', ')}`)
